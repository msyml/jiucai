const seen = new Set<string>();
export const STOCKS: StockInfo[] = STOCK_RAW
  .filter(([code]) => {
    if (seen.has(code)) return false;
    seen.add(code);
    return true;
  })
  .filter(([code]) => !code.startsWith('hk')) // 排除港股
  .map(([code, name, sector, note]) => ({
    code,
    name,
    sector,
    market: getMarket(code),
    note: note || '',
  }));

